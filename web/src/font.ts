/** Large 5x7 letters centered on x (titles). */
export function drawBig(s: string, x: number, y: number, clr: number, px: number, shadow = -1): void {
  s = s.toUpperCase();
  x = x - Math.trunc(((s.length * 6 - 1) * px) / 2);
  if (shadow < 0) shadow = RGB(12, 10, 18);
  for (let layer = 0; layer <= 1; layer++) {
    const col = layer === 0 ? shadow : clr;
    for (let k = 0; k < s.length; k++) {
      const bits = big.get(s[k]);
      const ox = x + k * 6 * px + (1 - layer) * Math.trunc(px / 2) + (1 - layer);
      if (!bits) continue;
      for (let r = 0; r < 7; r++)
        for (let c = 0; c < 5; c++)
          if (bits[r * 5 + c] === "1")
            R.fillRect(ox + c * px, y + r * px + (1 - layer) * (Math.trunc(px / 2) + 1), px + (px >= 3 ? 1 : 0), px, col);
    }
  }
}

export function textWidth(s: string, px: number): number {
  return s.length ? (s.length * 4 - 1) * px : 0;
}

/** Text with its top-left at (x, y). alignMode: 0 left, 1 center, 2 right. */
export function drawText(s: string, x: number, y: number, clr: number, px = 1, alignMode = 0): void {
  s = s.toUpperCase();
  if (alignMode === 1) x = x - Math.trunc(textWidth(s, px) / 2);
  if (alignMode === 2) x = x - textWidth(s, px);
  for (let layer = 0; layer <= 1; layer++) {
    const col = layer === 0 ? RGB(12, 10, 18) : clr;
    for (let k = 0; k < s.length; k++) {
      const bits = glyph.get(s[k]);
      if (!bits) continue;
      const ox = x + k * 4 * px;
      for (let r = 0; r < 5; r++)
        for (let c = 0; c < 3; c++)
          if (bits[r * 3 + c] === "1") {
            if (layer === 0) R.fillRect(ox + c * px + 1, y + r * px + 1, px, px, col);
            else R.fillRect(ox + c * px, y + r * px, px, px, col);
          }
    }
  }
}
