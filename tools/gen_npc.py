"""Story NPC sprites (classic chunky pixels, same format as the fighters): writes web/data/npc.txt.
  python3 tools/gen_npc.py
"""
import os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PAL = {"k": "1B1626", "h": "22202A", "s": "F2C6A0", "S": "C98D6B", "w": "D9D2C0", "W": "A79F8E",
       "r": "8C3A2E", "p": "6A6058", "P": "4D453F", "f": "9A7A4A"}
HEAD = """\
.....kk.......
....khhk......
....khhk......
...kkhhkk.....
..khhhhhhk....
.khhhhhhhhk...
.khhhhhhsssk..
.khhhhhssssk..
.khhhhsskssk..
.khhhhssssSk..
..khhhsssSk...
...kkSSSkk....""".split("\n")
BODY = """\
...kwwwwk.....
..kwwwwwwk....
..kWwwwwwk....
..kWwwwwskk...
..krrrrrrk....
..kWwwwwwk....
...kppppk.....""".split("\n")
LEGS = {
 "stand": """\
...kpppPk.....
...kpkkPk.....
...kpk.kPk....
..kffk.kffk...
..kkkk.kkkk...""",
 "stepA": """\
...kpppPk.....
..kppkkPPk....
.kppk...kPk...
kffk.....kffk.
kkkk.....kkkk.""",
 "stepB": """\
...kpppPk.....
...kpkPPk.....
...kpkkffk....
..kffk.kkk....
..kkkk........""",
}
def frame(legs, bob=0):
    up = HEAD + BODY
    rows = up + LEGS[legs].split("\n")
    if bob:   # upper body one pixel lower (breathing / step)
        rows = ["." * 14] + up[:-1] + LEGS[legs].split("\n")
        rows = rows[:len(up)] + LEGS[legs].split("\n")
        rows[0] = "." * 14
    return rows
frames = {"arong_idle_0": frame("stand"), "arong_idle_1": frame("stand", 1),
          "arong_walk_0": frame("stepA"), "arong_walk_1": frame("stepB", 1), "arong_walk_2": frame("stepA"), "arong_walk_3": frame("stand", 1)}
out = ["# story NPC sprites - generated by tools/gen_npc.py, do not edit by hand"]
out += [f"PAL {k} {v}" for k, v in PAL.items()]
for n, rows in frames.items():
    h = len(rows)
    out.append(f"SPRITE {n} 14 {h} 6 {h - 1}")
    out += rows
out.append("ANIM arong_idle 8 arong_idle_0 arong_idle_1")
out.append("ANIM arong_walk 3 arong_walk_0 arong_walk_1 arong_walk_2 arong_walk_3")
open(os.path.join(ROOT, "web", "data", "npc.txt"), "w").write("\n".join(out) + "\n")
print("npc.txt:", len(frames), "frames")
